from sqlmodel import Field

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin


class Address(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for a postal address.

    Addresses are created as part of organization creation and are not
    exposed through a standalone API.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the address (internal use only).
        Auto-generated by the database.
    guid : uuid.UUID
        Globally unique identifier for the address. Safe for external
        sharing and API responses.
    address_line_1 : str
        Primary address line (street/building). Required.
    address_line_2 : str | None, optional
        Secondary address line (unit/suite).
    landmark : str | None, optional
        Nearby landmark to aid navigation.
    city : str
        City name. Required, indexed.
    state : str
        State/province name. Required, indexed.
    country : str
        Country name. Required, indexed.
    postal_code : str
        Postal/ZIP code. Required.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "addresses"  # type: ignore

    id: int | None = Field(default=None, primary_key=True, index=True)
    address_line_1: str = Field(max_length=255, nullable=False)
    address_line_2: str | None = Field(default=None, max_length=255)
    landmark: str | None = Field(default=None, max_length=255)
    city: str = Field(max_length=100, nullable=False, index=True)
    state: str = Field(max_length=100, nullable=False, index=True)
    country: str = Field(max_length=100, nullable=False, index=True)
    postal_code: str = Field(max_length=20, nullable=False)


__all__ = [
    "Address",
]
