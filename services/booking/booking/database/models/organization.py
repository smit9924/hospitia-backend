from sqlmodel import Field, Relationship

from .address import Address
from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin
from .organization_type import OrganizationType


class Organization(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for an organization (NGO / guest-house operator).

    Attributes
    ----------
    id : int | None
        Primary key identifier for the organization (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the organization. Unique. Always used
        for external references and API responses.
    name : str
        Organization name. Indexed.
    description : str | None, optional
        Optional organization description.
    organization_type_id : int
        Foreign key to `organization_types.id`.
    address_id : int
        Foreign key to `addresses.id`. One-to-one: each organization has
        exactly one address.
    is_active : bool
        Whether the organization is active and available for booking.
        Soft-delete flag: deleting an organization sets this to False rather
        than removing the row.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.

    Notes
    -----
    - Always use `guid` for external references and API responses.
    - Use `id` only for internal database operations and relationships.
    - Booking-availability queries must filter on `is_active`.
    """

    __tablename__ = "organizations"  # type: ignore

    id: int | None = Field(default=None, primary_key=True, index=True)
    name: str = Field(max_length=255, nullable=False, index=True)
    description: str | None = Field(default=None, max_length=1000)
    organization_type_id: int = Field(foreign_key="organization_types.id", nullable=False, index=True)
    address_id: int = Field(foreign_key="addresses.id", nullable=False, unique=True, index=True)
    is_active: bool = Field(default=True, nullable=False, index=True)

    organization_type: OrganizationType = Relationship()
    address: Address = Relationship()


__all__ = [
    "Organization",
]
