from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import CheckConstraint, Index, Integer, Numeric, SmallInteger, String
from sqlmodel import Field, Relationship

from booking.types.enums import BookingStatus, UserType

from .base import SQLModel
from .currency_unit import CurrencyUnit
from .mixins import AuditMixin, GUIDMixin
from .organization import Organization
from .room import Room
from .users import UsersReplica

# Bounds shared by the database constraints and the API validation.
BOOKING_REFERENCE_MAX_LENGTH = 20
BOOKING_MIN_NIGHTS = 1
BOOKING_MAX_NIGHTS = 90
BOOKING_NOTES_MAX_LENGTH = 1000
BOOKING_CANCELLATION_REASON_MAX_LENGTH = 500
BOOKING_MAX_TOTAL_AMOUNT = Decimal("99999999999.99")

_BOOKING_STATUS_VALUES = ", ".join(f"'{status.value}'" for status in BookingStatus)


class Booking(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for a stay booked in one room of an organization.

    A booking covers the nights from `check_in_date` up to (not including)
    `check_out_date`. Its guests are linked through `BookingGuestMapping`.
    Bookings are never deleted: cancelling is the only way to withdraw one.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the booking (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the booking. Unique. Always used for
        external references and API responses.
    reference : str
        Human-friendly unique reference such as "BK-2026-000123". Never
        changes after creation.
    organization_id : int
        Foreign key to `organizations.id`: the organization of the booked
        room. Deletion of the organization is restricted.
    room_id : int
        Foreign key to `rooms.id`: the booked room. Deletion of the room is
        restricted.
    booked_by : int
        Foreign key to `usersreplica.id`: the user who registered the
        booking (an admin, owner or manager today; a customer in future).
        Deletion of the user is restricted.
    booked_by_role : UserType
        Role of `booked_by` when the booking was registered.
    check_in_date, check_out_date : date
        First night and departure day; `check_out_date` is after
        `check_in_date`.
    nights : int
        Number of nights, from 1 to 90; always
        `check_out_date - check_in_date`.
    guest_count : int
        Number of linked guests (primary + secondary), at least 1.
    status : BookingStatus
        Lifecycle status; defaults to `BookingStatus.CONFIRMED`.
    cost_per_night : Decimal
        Snapshot of the room type's nightly cost when the stay was priced.
    total_amount : Decimal
        `nights * cost_per_night`, stored with two decimal places.
    currency_unit_id : int
        Foreign key to `currency_units.id`: currency of the price snapshot.
        Deletion of the currency is restricted.
    notes : str | None, optional
        Free-text notes, at most 1000 characters.
    checked_in_at, checked_out_at, cancelled_at : datetime | None
        When the booking moved to that status, if it did.
    checked_in_by, checked_out_by, cancelled_by : int | None
        Foreign keys to `usersreplica.id`: who performed that transition.
        Deletion of the user is restricted.
    cancellation_reason : str | None, optional
        Optional reason given when cancelling, at most 500 characters.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "bookings"  # type: ignore
    __table_args__ = (
        CheckConstraint("check_out_date > check_in_date", name="ck_bookings_dates_order"),
        CheckConstraint(
            f"nights BETWEEN {BOOKING_MIN_NIGHTS} AND {BOOKING_MAX_NIGHTS}",
            name="ck_bookings_nights_range",
        ),
        CheckConstraint("guest_count >= 1", name="ck_bookings_guest_count_positive"),
        CheckConstraint(f"status IN ({_BOOKING_STATUS_VALUES})", name="ck_bookings_status"),
        CheckConstraint("cost_per_night >= 0", name="ck_bookings_cost_per_night_positive"),
        CheckConstraint("total_amount >= 0", name="ck_bookings_total_amount_positive"),
        Index("ix_bookings_organization_status", "organization_id", "status"),
        Index("ix_bookings_room_stay", "room_id", "check_in_date", "check_out_date"),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    reference: str = Field(max_length=BOOKING_REFERENCE_MAX_LENGTH, nullable=False, unique=True, index=True)
    organization_id: int = Field(foreign_key="organizations.id", nullable=False, index=True, ondelete="RESTRICT")
    room_id: int = Field(foreign_key="rooms.id", nullable=False, index=True, ondelete="RESTRICT")
    booked_by: int = Field(foreign_key="usersreplica.id", nullable=False, index=True, ondelete="RESTRICT")
    booked_by_role: UserType = Field(nullable=False, sa_type=Integer)
    check_in_date: date = Field(nullable=False, index=True)
    check_out_date: date = Field(nullable=False)
    nights: int = Field(sa_type=SmallInteger, nullable=False)  # type: ignore[call-overload]
    guest_count: int = Field(sa_type=SmallInteger, nullable=False)  # type: ignore[call-overload]
    status: BookingStatus = Field(
        default=BookingStatus.CONFIRMED,
        sa_type=String(20),  # type: ignore[call-overload]
        nullable=False,
    )
    cost_per_night: Decimal = Field(sa_type=Numeric(11, 2), nullable=False)  # type: ignore[call-overload]
    total_amount: Decimal = Field(sa_type=Numeric(13, 2), nullable=False)  # type: ignore[call-overload]
    currency_unit_id: int = Field(foreign_key="currency_units.id", nullable=False, index=True, ondelete="RESTRICT")
    notes: str | None = Field(default=None, max_length=BOOKING_NOTES_MAX_LENGTH)
    checked_in_at: datetime | None = Field(default=None)
    checked_in_by: int | None = Field(default=None, foreign_key="usersreplica.id", ondelete="RESTRICT")
    checked_out_at: datetime | None = Field(default=None)
    checked_out_by: int | None = Field(default=None, foreign_key="usersreplica.id", ondelete="RESTRICT")
    cancelled_at: datetime | None = Field(default=None)
    cancelled_by: int | None = Field(default=None, foreign_key="usersreplica.id", ondelete="RESTRICT")
    cancellation_reason: str | None = Field(default=None, max_length=BOOKING_CANCELLATION_REASON_MAX_LENGTH)

    organization: Organization = Relationship()
    room: Room = Relationship()
    currency_unit: CurrencyUnit = Relationship()
    # Several columns reference `usersreplica`, so each relationship names its own.
    booker: UsersReplica = Relationship(sa_relationship_kwargs={"foreign_keys": "[Booking.booked_by]"})
    checked_in_user: UsersReplica | None = Relationship(
        sa_relationship_kwargs={"foreign_keys": "[Booking.checked_in_by]"}
    )
    checked_out_user: UsersReplica | None = Relationship(
        sa_relationship_kwargs={"foreign_keys": "[Booking.checked_out_by]"}
    )
    cancelled_user: UsersReplica | None = Relationship(
        sa_relationship_kwargs={"foreign_keys": "[Booking.cancelled_by]"}
    )


