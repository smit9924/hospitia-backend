from sqlmodel import Field

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin


class OrganizationType(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for an organization type (e.g. NGO, Guest House, OTHER).

    Attributes
    ----------
    id : int | None
        Primary key identifier for the organization type (internal use only).
        Auto-generated by the database.
    guid : uuid.UUID
        Globally unique identifier for the organization type. Unique. Safe
        for external sharing and API responses.
    name : str
        Organization type name. Unique, indexed.
    description : str | None, optional
        Optional description of the organization type.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "organization_types"  # type: ignore

    id: int | None = Field(default=None, primary_key=True, index=True)
    name: str = Field(max_length=100, nullable=False, unique=True, index=True)
    description: str | None = Field(default=None, max_length=500)


__all__ = [
    "OrganizationType",
]
