from sqlalchemy import Index, text
from sqlmodel import Field

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin


class CurrencyUnit(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for an ISO 4217 currency unit (e.g. INR, USD, EUR).

    Attributes
    ----------
    id : int | None
        Primary key identifier for the currency unit (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the currency unit. Unique. Always
        used for external references and API responses.
    currency_code : str
        ISO 4217 alphabetic code, three uppercase letters (e.g. "INR").
        Unique among active currency units.
    numeric_code : str
        ISO 4217 numeric code, three digits kept as text so leading zeros
        survive (e.g. "036" for AUD). Unique among active currency units.
    currency_name : str
        Human-readable currency name (e.g. "Indian Rupee").
    minor_unit : int | None, optional
        Number of decimal places of the currency (e.g. 2 for INR, 0 for
        JPY). ``None`` when ISO 4217 defines none ("N.A.").
    is_active : bool
        Soft-delete flag: deleting a currency unit sets this to False
        rather than removing the row, so records that reference it keep
        a valid foreign key.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.

    Notes
    -----
    Codes are unique only among active rows (partial unique indexes), so a
    deleted currency unit can be added again later.
    """

    __tablename__ = "currency_units"  # type: ignore
    __table_args__ = (
        Index(
            "uq_currency_units_active_currency_code",
            "currency_code",
            unique=True,
            postgresql_where=text("is_active"),
            sqlite_where=text("is_active"),
        ),
        Index(
            "uq_currency_units_active_numeric_code",
            "numeric_code",
            unique=True,
            postgresql_where=text("is_active"),
            sqlite_where=text("is_active"),
        ),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    currency_code: str = Field(min_length=3, max_length=3, nullable=False, index=True)
    numeric_code: str = Field(min_length=3, max_length=3, nullable=False)
    currency_name: str = Field(max_length=100, nullable=False, index=True)
    minor_unit: int | None = Field(default=None, nullable=True)
    is_active: bool = Field(default=True, nullable=False, index=True)


__all__ = [
    "CurrencyUnit",
]
