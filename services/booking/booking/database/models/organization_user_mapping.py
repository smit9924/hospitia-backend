from sqlalchemy import UniqueConstraint
from sqlmodel import Field, Relationship

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin
from .organization import Organization


class OrganizationUserMapping(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model mapping a user to an organization with a role.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the mapping (internal use only).
        Auto-generated by the database.
    guid : uuid.UUID
        Globally unique identifier for the mapping. Unique. Safe for
        external sharing and API responses.
    organization_id : int
        Foreign key to `organizations.id`. Deletion of a referenced user or
        organization is restricted (`ondelete="RESTRICT"`) so a mapping can
        never be silently orphaned.
    user_id : int
        Foreign key to `usersreplica.id` (the Booking Service's local user
        replica) identifying the mapped user.
    is_active : bool
        Whether the mapping is currently active. Used to deactivate a
        mapping (e.g. during owner replacement) without losing history.
        Every organization must have at least one active OWNER mapping at
        all times.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.

    Notes
    -----
    Unique on (organization_id, user_id) to prevent duplicate
    user-organization mappings.
    """

    __tablename__ = "organization_user_mapping"  # type: ignore
    __table_args__ = (
        UniqueConstraint("organization_id", "user_id", name="uq_org_user_mapping_org_user"),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    organization_id: int = Field(foreign_key="organizations.id", nullable=False, index=True, ondelete="RESTRICT")
    user_id: int = Field(foreign_key="usersreplica.id", nullable=False, index=True, ondelete="RESTRICT")
    is_active: bool = Field(default=True, nullable=False, index=True)

    organization: Organization = Relationship()


__all__ = [
    "OrganizationUserMapping",
]
