from sqlalchemy import Index, SmallInteger, UniqueConstraint, text
from sqlmodel import Field, Relationship

from .base import SQLModel
from .booking import Booking
from .guest_detail import GuestDetail
from .mixins import AuditMixin, GUIDMixin


class BookingGuestMapping(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model linking a booking to one of its guests.

    Every booking has exactly one primary guest (the contact person) and may
    have secondary guests; together they never exceed the room's capacity.
    A guest belongs to exactly one booking.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the mapping (internal use only).
        Auto-generated by the database.
    guid : uuid.UUID
        Globally unique identifier for the mapping. Unique.
    booking_id : int
        Foreign key to `bookings.id`. Deletion of the booking is restricted.
    guest_id : int
        Foreign key to `guest_details.id`. Unique: a guest belongs to one
        booking. Deletion of the guest is restricted, so remove the mapping
        first.
    is_primary : bool
        True for the booking's primary guest; at most one per booking.
    position : int
        Display order within the booking; the primary guest is 0.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "booking_guest_mappings"  # type: ignore
    __table_args__ = (
        UniqueConstraint("booking_id", "position", name="uq_booking_guest_mappings_booking_position"),
        Index(
            "uq_booking_guest_mappings_one_primary",
            "booking_id",
            unique=True,
            postgresql_where=text("is_primary"),
            sqlite_where=text("is_primary"),
        ),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    booking_id: int = Field(foreign_key="bookings.id", nullable=False, index=True, ondelete="RESTRICT")
    guest_id: int = Field(foreign_key="guest_details.id", nullable=False, unique=True, index=True, ondelete="RESTRICT")
    is_primary: bool = Field(default=False, nullable=False)
    position: int = Field(sa_type=SmallInteger, nullable=False)  # type: ignore[call-overload]

    booking: Booking = Relationship()
    guest: GuestDetail = Relationship()


__all__ = [
    "BookingGuestMapping",
]
