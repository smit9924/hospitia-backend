from decimal import Decimal

from sqlalchemy import CheckConstraint, Index, Numeric, text
from sqlmodel import Field, Relationship

from .base import SQLModel
from .currency_unit import CurrencyUnit
from .mixins import AuditMixin, GUIDMixin
from .organization import Organization

# Bounds shared by the database constraints and the API validation.
ROOM_TYPE_MIN_CAPACITY = 1
ROOM_TYPE_MAX_CAPACITY = 1000
ROOM_TYPE_MAX_COST_PER_NIGHT = Decimal("999999999.99")


class RoomType(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for a room type of an organization (e.g. "Deluxe double").

    A room type describes a category of rooms (capacity, nightly cost and
    amenities); it is not an individual room.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the room type (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the room type. Unique. Always used
        for external references and API responses.
    organization_id : int
        Foreign key to `organizations.id` owning the room type. Never
        changes after creation. Deletion of the organization is restricted
        (`ondelete="RESTRICT"`).
    name : str
        Room type name. Unique (case-insensitively) among the active room
        types of one organization.
    description : str | None, optional
        Optional room type description.
    capacity : int
        Maximum number of guests, from 1 to 1000.
    cost_per_night : Decimal
        Price of one night, from 0 (free stay) to 999,999,999.99, stored with
        exactly two decimal places (``NUMERIC(11, 2)``).
    currency_unit_id : int
        Foreign key to `currency_units.id`: the currency of
        `cost_per_night`. Deletion of the currency is restricted.
    is_active : bool
        Soft-delete flag: deleting a room type sets this to False rather
        than removing the row.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.

    Notes
    -----
    Amenities are linked through `RoomTypeAmenityMapping`.
    """

    __tablename__ = "room_types"  # type: ignore
    __table_args__ = (
        CheckConstraint(
            f"capacity BETWEEN {ROOM_TYPE_MIN_CAPACITY} AND {ROOM_TYPE_MAX_CAPACITY}",
            name="ck_room_types_capacity_range",
        ),
        CheckConstraint(
            f"cost_per_night >= 0 AND cost_per_night <= {ROOM_TYPE_MAX_COST_PER_NIGHT}",
            name="ck_room_types_cost_per_night_range",
        ),
        Index(
            "uq_room_types_active_organization_name",
            "organization_id",
            text("lower(name)"),
            unique=True,
            postgresql_where=text("is_active"),
            sqlite_where=text("is_active"),
        ),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    organization_id: int = Field(foreign_key="organizations.id", nullable=False, index=True, ondelete="RESTRICT")
    name: str = Field(max_length=100, nullable=False, index=True)
    description: str | None = Field(default=None, max_length=500)
    capacity: int = Field(nullable=False)
    cost_per_night: Decimal = Field(sa_type=Numeric(11, 2), nullable=False)  # type: ignore[call-overload]
    currency_unit_id: int = Field(foreign_key="currency_units.id", nullable=False, index=True, ondelete="RESTRICT")
    is_active: bool = Field(default=True, nullable=False, index=True)

    organization: Organization = Relationship()
    currency_unit: CurrencyUnit = Relationship()


__all__ = [
    "ROOM_TYPE_MAX_CAPACITY",
    "ROOM_TYPE_MAX_COST_PER_NIGHT",
    "ROOM_TYPE_MIN_CAPACITY",
    "RoomType",
]
