from sqlalchemy import CheckConstraint, Index, SmallInteger, String, text
from sqlmodel import Field, Relationship

from booking.types.enums import RoomStatus

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin
from .organization import Organization
from .room_type import RoomType

# Bounds shared by the database constraints and the API validation.
ROOM_NUMBER_MAX_LENGTH = 20
# Letters, digits, "-" and "/" only (e.g. "101", "A-12", "B2/04").
ROOM_NUMBER_PATTERN = r"^[A-Za-z0-9/-]+$"
ROOM_MIN_FLOOR = -500
ROOM_MAX_FLOOR = 500
ROOM_NOTES_MAX_LENGTH = 500

_ROOM_STATUS_VALUES = ", ".join(f"'{status.value}'" for status in RoomStatus)


class Room(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for an individual room of an organization (e.g. room "101").

    Every room belongs to one room type of the same organization, which
    defines its capacity, price and amenities.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the room (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the room. Unique. Always used for
        external references and API responses.
    organization_id : int
        Foreign key to `organizations.id` owning the room. Never changes
        after creation. Deletion of the organization is restricted.
    room_type_id : int
        Foreign key to `room_types.id`: the room type of the same
        organization. Deletion of the room type is restricted.
    room_number : str
        Room number such as "101" or "A-12": 1 to 20 letters, digits, "-"
        or "/". Unique (case-insensitively) among the active rooms of one
        organization.
    floor : int
        Floor from -500 to 500. 0 is the ground floor; negative numbers are
        basement levels (-1 is shown as "B1").
    status : RoomStatus
        Operational status; defaults to `RoomStatus.AVAILABLE`.
    notes : str | None, optional
        Optional free-text notes, at most 500 characters.
    is_active : bool
        Soft-delete flag: deleting a room sets this to False rather than
        removing the row.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "rooms"  # type: ignore
    __table_args__ = (
        CheckConstraint(
            f"floor BETWEEN {ROOM_MIN_FLOOR} AND {ROOM_MAX_FLOOR}",
            name="ck_rooms_floor_range",
        ),
        CheckConstraint(f"status IN ({_ROOM_STATUS_VALUES})", name="ck_rooms_status"),
        # PostgreSQL regex (the service's database); the API validates the same rule.
        CheckConstraint(
            f"room_number ~ '^[A-Za-z0-9/-]{{1,{ROOM_NUMBER_MAX_LENGTH}}}$'",
            name="ck_rooms_room_number_format",
        ),
        Index(
            "uq_rooms_active_organization_room_number",
            "organization_id",
            text("lower(room_number)"),
            unique=True,
            postgresql_where=text("is_active"),
            sqlite_where=text("is_active"),
        ),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    organization_id: int = Field(foreign_key="organizations.id", nullable=False, index=True, ondelete="RESTRICT")
    room_type_id: int = Field(foreign_key="room_types.id", nullable=False, index=True, ondelete="RESTRICT")
    room_number: str = Field(max_length=ROOM_NUMBER_MAX_LENGTH, nullable=False, index=True)
    floor: int = Field(sa_type=SmallInteger, nullable=False)  # type: ignore[call-overload]
    status: RoomStatus = Field(
        default=RoomStatus.AVAILABLE,
        sa_type=String(20),  # type: ignore[call-overload]
        nullable=False,
    )
    notes: str | None = Field(default=None, max_length=ROOM_NOTES_MAX_LENGTH)
    is_active: bool = Field(default=True, nullable=False, index=True)

    organization: Organization = Relationship()
    room_type: RoomType = Relationship()


__all__ = [
    "ROOM_MAX_FLOOR",
    "ROOM_MIN_FLOOR",
    "ROOM_NOTES_MAX_LENGTH",
    "ROOM_NUMBER_MAX_LENGTH",
    "ROOM_NUMBER_PATTERN",
    "Room",
]
