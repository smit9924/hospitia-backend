from sqlalchemy import Index, text
from sqlmodel import Field, Relationship

from .base import SQLModel
from .mixins import AuditMixin, GUIDMixin
from .organization import Organization


class RoomAmenity(AuditMixin, GUIDMixin, SQLModel, table=True):
    """
    Database model for a room-level amenity (e.g. TV, fridge, geyser).

    An amenity is either a system-wide default, managed by admins and
    offered to every organization, or a custom amenity that belongs to a
    single organization.

    Attributes
    ----------
    id : int | None
        Primary key identifier for the amenity (internal use only).
        Auto-generated by the database. Never exposed through the API.
    guid : uuid.UUID
        Globally unique identifier for the amenity. Unique. Always used for
        external references and API responses.
    name : str
        Amenity name. Unique (case-insensitively) among active default
        amenities, and among the active custom amenities of one
        organization. A custom name may not repeat a default name; that
        cross-scope rule is enforced by the service layer.
    description : str | None, optional
        Optional amenity description.
    organization_id : int | None, optional
        Foreign key to `organizations.id` owning a custom amenity; ``None``
        for a default amenity. Deletion of a referenced organization is
        restricted (`ondelete="RESTRICT"`).
    is_active : bool
        Soft-delete flag: deleting an amenity sets this to False rather
        than removing the row.
    created_at, updated_at, created_by, updated_by
        Audit fields, see `AuditMixin`.
    """

    __tablename__ = "room_amenities"  # type: ignore
    __table_args__ = (
        Index(
            "uq_room_amenities_active_default_name",
            text("lower(name)"),
            unique=True,
            postgresql_where=text("is_active AND organization_id IS NULL"),
            sqlite_where=text("is_active AND organization_id IS NULL"),
        ),
        Index(
            "uq_room_amenities_active_custom_name",
            "organization_id",
            text("lower(name)"),
            unique=True,
            postgresql_where=text("is_active AND organization_id IS NOT NULL"),
            sqlite_where=text("is_active AND organization_id IS NOT NULL"),
        ),
    )

    id: int | None = Field(default=None, primary_key=True, index=True)
    name: str = Field(max_length=100, nullable=False, index=True)
    description: str | None = Field(default=None, max_length=500)
    organization_id: int | None = Field(
        default=None,
        foreign_key="organizations.id",
        nullable=True,
        index=True,
        ondelete="RESTRICT",
    )
    is_active: bool = Field(default=True, nullable=False, index=True)

    organization: Organization | None = Relationship()

    @property
    def is_default(self) -> bool:
        """Whether this is a system-wide default amenity (not tied to an organization)."""
        return self.organization_id is None


__all__ = [
    "RoomAmenity",
]
